// Builds the inline US map SVG for the About tab and writes it into index.html
// between <!-- MAP:START --> and <!-- MAP:END -->.
//
// One time tooling. Nothing here ships to visitors; only the SVG it writes does.
// To rerun (from any temp folder OUTSIDE the site, so node_modules never lands in it):
//
//   mkdir /tmp/mapgen && cd /tmp/mapgen && npm init -y
//   npm install d3-geo@3.1.1 topojson-client@3.1.0 topojson-simplify@3.0.3 us-atlas@3.0.1
//   node /path/to/PersonalSite/tools/build-map.mjs /path/to/PersonalSite/index.html
//
// To change which states are visited or where the markers sit, edit NOT_VISITED
// or PLACES below and rerun. Fill colors live in styles.css (--map-visited,
// --map-unvisited), so an all blue map is a one line CSS change, no rerun needed.

import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";

const require = createRequire(process.cwd() + "/");
const { geoPath, geoAlbersUsa } = require("d3-geo");
const topojson = require("topojson-client");
const simplify = require("topojson-simplify");

const target = process.argv[2];
if (!target) throw new Error("Usage: node build-map.mjs path/to/index.html");

const NOT_VISITED = ["AK", "ME", "VT", "MS", "MA"];

// Where Kimball has lived. id matches the <li> in the text list in index.html,
// which also supplies the tooltip card text.
const PLACES = [
  { id: "place-provo",     label: "Provo, Utah",                       lat: 40.2338, lon: -111.6585 },
  { id: "place-spokane",   label: "Spokane, Washington",               lat: 47.6588, lon: -117.4260 },
  { id: "place-durham",    label: "Durham, North Carolina",            lat: 35.9940, lon: -78.8986 },
  { id: "place-bay",       label: "San Francisco and Oakland, California", lat: 37.7897, lon: -122.3442 },
];
const HOME = { id: "place-orono", label: "Orono, Minnesota, my hometown", lat: 44.9711, lon: -93.6044 };

const FIPS = {
  "01":"AL","02":"AK","04":"AZ","05":"AR","06":"CA","08":"CO","09":"CT","10":"DE","12":"FL","13":"GA",
  "15":"HI","16":"ID","17":"IL","18":"IN","19":"IA","20":"KS","21":"KY","22":"LA","23":"ME","24":"MD",
  "25":"MA","26":"MI","27":"MN","28":"MS","29":"MO","30":"MT","31":"NE","32":"NV","33":"NH","34":"NJ",
  "35":"NM","36":"NY","37":"NC","38":"ND","39":"OH","40":"OK","41":"OR","42":"PA","44":"RI","45":"SC",
  "46":"SD","47":"TN","48":"TX","49":"UT","50":"VT","51":"VA","53":"WA","54":"WV","55":"WI","56":"WY",
};

// states-albers-10m is pre projected to 975 x 610 with the Alaska and Hawaii
// insets; this projection matches it, for placing the markers.
let topo = JSON.parse(readFileSync(require.resolve("us-atlas/states-albers-10m.json"), "utf8"));
topo = simplify.simplify(simplify.presimplify(topo), 2);
const path = geoPath();                       // identity: data is already projected
const project = geoAlbersUsa().scale(1300).translate([487.5, 305]);

const round = (d) => d.replace(/(\d+\.\d)\d+/g, "$1");

const states = topojson.feature(topo, topo.objects.states).features
  .filter((f) => FIPS[f.id])                  // 50 states; drops DC and territories
  .sort((a, b) => a.properties.name.localeCompare(b.properties.name))
  .map((f) => {
    const code = FIPS[f.id];
    const visited = !NOT_VISITED.includes(code);
    const name = f.properties.name;
    return `<path class="usmap__state ${visited ? "is-visited" : "is-unvisited"}" data-state="${code}" ` +
      `data-name="${name}" data-status="${visited ? "Visited" : "Not yet"}" d="${round(path(f))}">` +
      `<title>${name}: ${visited ? "visited" : "not yet visited"}</title></path>`;
  });

const borders = round(path(topojson.mesh(topo, topo.objects.states, (a, b) => a !== b)));

const pct = ([x, y]) => `left:${(x / 975 * 100).toFixed(2)}%;top:${(y / 610 * 100).toFixed(2)}%`;
const marker = (p, star) => {
  const xy = project([p.lon, p.lat]);
  const icon = star
    ? `<svg viewBox="0 0 24 24" aria-hidden="true"><path d="m12 2.5 2.9 6 6.6.9-4.8 4.6 1.2 6.5L12 17.4l-5.9 3.1 1.2-6.5L2.5 9.4l6.6-.9z"/></svg>`
    : `<svg viewBox="0 0 24 24" aria-hidden="true"><circle cx="12" cy="12" r="7"/></svg>`;
  return `<button class="usmap__marker${star ? " usmap__marker--home" : ""}" type="button" style="${pct(xy)}" ` +
    `data-card="${p.id}" aria-label="${p.label}" aria-describedby="${p.id}">${icon}</button>`;
};

const svg = `<!-- MAP:START (generated by tools/build-map.mjs; edit that file and rerun, do not hand edit) -->
<div class="usmap" data-usmap>
  <svg class="usmap__svg" viewBox="0 0 975 610" role="img" aria-labelledby="usmap-title usmap-desc">
    <title id="usmap-title">Map of the United States showing the states Kimball has visited</title>
    <desc id="usmap-desc">${50 - NOT_VISITED.length} of 50 states are shaded as visited. The lists below the map name the states not yet visited and the places Kimball has lived.</desc>
    <g class="usmap__states">
      ${states.join("\n      ")}
    </g>
    <path class="usmap__borders" d="${borders}"/>
  </svg>
  ${PLACES.map((p) => marker(p, false)).join("\n  ")}
  ${marker(HOME, true)}
  <div class="tip" role="tooltip" id="usmap-tip" hidden></div>
</div>
<!-- MAP:END -->`;

const html = readFileSync(target, "utf8");
const re = /<!-- MAP:START[\s\S]*?<!-- MAP:END -->/;
if (!re.test(html)) throw new Error("Markers <!-- MAP:START --> and <!-- MAP:END --> not found in " + target);
writeFileSync(target, html.replace(re, svg));
console.log(`Wrote map: ${states.length} states, ${svg.length} bytes`);
